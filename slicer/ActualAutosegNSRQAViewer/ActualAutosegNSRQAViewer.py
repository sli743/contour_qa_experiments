import json
import logging
import os
from pathlib import Path

import vtk, qt, ctk, slicer
from slicer.ScriptedLoadableModule import *


DEFAULT_ROOT = r"D:\aiqa\contour_QA\all_roi_NSRQA_study\actual_autoseg_regression"

PRIMARY_SPECS = [
    ("approved", "Approved", "approved.nii.gz", (0.00, 0.85, 1.00)),
    ("autoseg", "Autoseg input", "autoseg_input.nii.gz", (1.00, 0.55, 0.00)),
    ("recon", "NSR-QA reconstruction", "nsrqa_reconstruction.nii.gz", (0.30, 0.85, 0.25)),
]

DIAGNOSTIC_SPECS = [
    ("true_missing", "Autoseg missing vs approved", "missing_autoseg_vs_approved.nii.gz", (0.00, 0.90, 1.00)),
    ("true_excess", "Autoseg excess vs approved", "excess_autoseg_vs_approved.nii.gz", (1.00, 0.00, 0.85)),
    ("qa_missing", "Input missing vs reconstruction", "missing_input_vs_reconstruction.nii.gz", (0.75, 0.85, 0.10)),
    ("qa_excess", "Input excess vs reconstruction", "excess_input_vs_reconstruction.nii.gz", (1.00, 0.20, 0.15)),
]


class ActualAutosegNSRQAViewer(ScriptedLoadableModule):
    def __init__(self, parent):
        ScriptedLoadableModule.__init__(self, parent)
        self.parent.title = "Actual Autoseg NSR-QA Viewer"
        self.parent.categories = ["Segmentation"]
        self.parent.dependencies = ["Segmentations"]
        self.parent.contributors = ["OpenAI"]
        self.parent.helpText = """
Inspect actual clinical autosegmentation inputs, approved contours, NSR-QA
reconstructions, and error/disagreement masks generated by the regression
experiment. Cases can be browsed by localization mode, ROI, split, and patient.
"""
        self.parent.acknowledgementText = "Generated for the AIQA contour-QA workflow."


class ActualAutosegNSRQAViewerWidget(ScriptedLoadableModuleWidget):
    def setup(self):
        ScriptedLoadableModuleWidget.setup(self)
        self.logic = ActualAutosegNSRQAViewerLogic()
        self.caseIndex = {}
        self.loadedNodes = {"ct": None, "seg": None, "diag": None}
        self.primaryIds = {}
        self.diagIds = {}

        inputBox = ctk.ctkCollapsibleButton()
        inputBox.text = "Input"
        self.layout.addWidget(inputBox)
        form = qt.QFormLayout(inputBox)

        self.directoryButton = ctk.ctkPathLineEdit()
        self.directoryButton.filters = ctk.ctkPathLineEdit.Dirs
        self.directoryButton.settingKey = "ActualAutosegNSRQAViewer/rootDir"
        self.directoryButton.currentPath = DEFAULT_ROOT
        form.addRow("Experiment root:", self.directoryButton)

        self.scanButton = qt.QPushButton("Scan directory")
        form.addRow(self.scanButton)

        self.modeCombo = qt.QComboBox()
        form.addRow("Localization mode:", self.modeCombo)
        self.roiCombo = qt.QComboBox()
        form.addRow("ROI:", self.roiCombo)
        self.splitCombo = qt.QComboBox()
        form.addRow("Split:", self.splitCombo)
        self.patientCombo = qt.QComboBox()
        form.addRow("Patient:", self.patientCombo)

        row = qt.QHBoxLayout()
        self.loadButton = qt.QPushButton("Load selected case")
        self.clearButton = qt.QPushButton("Clear loaded nodes")
        row.addWidget(self.loadButton)
        row.addWidget(self.clearButton)
        form.addRow(row)

        visBox = ctk.ctkCollapsibleButton()
        visBox.text = "Visibility"
        self.layout.addWidget(visBox)
        visForm = qt.QFormLayout(visBox)

        self.showCT = qt.QCheckBox()
        self.showCT.checked = True
        visForm.addRow("Show CT:", self.showCT)

        self.primaryChecks = {}
        for key, label, _file, color in PRIMARY_SPECS:
            cb = qt.QCheckBox()
            cb.checked = True
            self.primaryChecks[key] = cb
            visForm.addRow(self._colorLabel(label, color), cb)

        self.diagChecks = {}
        for key, label, _file, color in DIAGNOSTIC_SPECS:
            cb = qt.QCheckBox()
            cb.checked = False
            self.diagChecks[key] = cb
            visForm.addRow(self._colorLabel(label, color), cb)

        self.opacity = ctk.ctkSliderWidget()
        self.opacity.minimum = 0.0
        self.opacity.maximum = 1.0
        self.opacity.singleStep = 0.05
        self.opacity.value = 0.30
        self.opacity.decimals = 2
        visForm.addRow("2D fill opacity:", self.opacity)

        self.thickness = ctk.ctkSliderWidget()
        self.thickness.minimum = 1
        self.thickness.maximum = 10
        self.thickness.singleStep = 1
        self.thickness.value = 1
        self.thickness.decimals = 0
        visForm.addRow("2D contour thickness:", self.thickness)

        self.show3D = qt.QCheckBox()
        self.show3D.checked = False
        visForm.addRow("Show contours in 3D:", self.show3D)

        self.fitButton = qt.QPushButton("Fit slice views")
        visForm.addRow(self.fitButton)

        metricBox = ctk.ctkCollapsibleButton()
        metricBox.text = "Case metrics"
        self.layout.addWidget(metricBox)
        metricLayout = qt.QVBoxLayout(metricBox)
        self.metricsLabel = qt.QLabel("Load a case to show metrics.")
        self.metricsLabel.wordWrap = True
        self.metricsLabel.setTextInteractionFlags(qt.Qt.TextSelectableByMouse)
        metricLayout.addWidget(self.metricsLabel)

        self.statusLabel = qt.QLabel("Select the experiment root and scan.")
        self.statusLabel.wordWrap = True
        self.layout.addWidget(self.statusLabel)
        self.layout.addStretch(1)

        self.scanButton.connect("clicked()", self.onScan)
        self.modeCombo.connect("currentIndexChanged(int)", self.onModeChanged)
        self.roiCombo.connect("currentIndexChanged(int)", self.onRoiChanged)
        self.splitCombo.connect("currentIndexChanged(int)", self.onSplitChanged)
        self.loadButton.connect("clicked()", self.onLoad)
        self.clearButton.connect("clicked()", self.clearLoadedNodes)
        self.fitButton.connect("clicked()", self.fitViews)
        self.showCT.connect("toggled(bool)", self.updateVisibility)
        self.opacity.connect("valueChanged(double)", self.updateVisibility)
        self.thickness.connect("valueChanged(double)", self.updateVisibility)
        self.show3D.connect("toggled(bool)", self.updateVisibility)
        for cb in list(self.primaryChecks.values()) + list(self.diagChecks.values()):
            cb.connect("toggled(bool)", self.updateVisibility)

        if os.path.isdir(DEFAULT_ROOT):
            self.onScan()

    @staticmethod
    def _colorLabel(text, color):
        r, g, b = [int(round(c * 255)) for c in color]
        label = qt.QLabel(text)
        label.setStyleSheet(f"QLabel {{ font-weight: 600; color: rgb({r},{g},{b}); }}")
        return label

    def cleanup(self):
        self.clearLoadedNodes()

    def onScan(self):
        self.caseIndex = self.logic.scanRoot(Path(self.directoryButton.currentPath))
        self.modeCombo.blockSignals(True)
        self.modeCombo.clear()
        for mode in sorted(self.caseIndex):
            self.modeCombo.addItem(mode)
        self.modeCombo.blockSignals(False)
        self.onModeChanged()
        n = self.logic.countCases(self.caseIndex)
        self.statusLabel.text = f"Found {n} case(s) across {len(self.caseIndex)} localization mode(s)."

    def onModeChanged(self, *_args):
        self.roiCombo.blockSignals(True)
        self.roiCombo.clear()
        mode = self.modeCombo.currentText
        for roi in sorted(self.caseIndex.get(mode, {}), key=str.lower):
            self.roiCombo.addItem(roi)
        self.roiCombo.blockSignals(False)
        self.onRoiChanged()

    def onRoiChanged(self, *_args):
        self.splitCombo.blockSignals(True)
        self.splitCombo.clear()
        mode = self.modeCombo.currentText
        roi = self.roiCombo.currentText
        splits = self.caseIndex.get(mode, {}).get(roi, {})
        for split in ("training1", "validation1", "testing1"):
            if split in splits:
                self.splitCombo.addItem(split)
        for split in sorted(set(splits) - {"training1", "validation1", "testing1"}):
            self.splitCombo.addItem(split)
        self.splitCombo.blockSignals(False)
        self.onSplitChanged()

    def onSplitChanged(self, *_args):
        self.patientCombo.clear()
        mode = self.modeCombo.currentText
        roi = self.roiCombo.currentText
        split = self.splitCombo.currentText
        cases = self.caseIndex.get(mode, {}).get(roi, {}).get(split, {})
        for pid in sorted(cases, key=self.logic.patientSortKey):
            self.patientCombo.addItem(pid)
        self.loadButton.enabled = bool(cases)

    def onLoad(self):
        mode = self.modeCombo.currentText
        roi = self.roiCombo.currentText
        split = self.splitCombo.currentText
        pid = self.patientCombo.currentText
        caseDir = self.caseIndex.get(mode, {}).get(roi, {}).get(split, {}).get(pid)
        if not caseDir:
            slicer.util.errorDisplay("No case found for the current selection.")
            return
        self.clearLoadedNodes()
        try:
            ct, seg, primaryIds, diag, diagIds, missing = self.logic.loadCase(caseDir, roi, pid)
            self.loadedNodes = {"ct": ct, "seg": seg, "diag": diag}
            self.primaryIds = primaryIds
            self.diagIds = diagIds
            slicer.util.setSliceViewerLayers(background=ct)
            self.updateVisibility()
            self.fitViews()
            self.metricsLabel.text = self.logic.formatMetrics(caseDir)
            msg = f"Loaded {mode} / {roi} / {split} / patient {pid}."
            if missing:
                msg += " Missing: " + ", ".join(missing)
            self.statusLabel.text = msg
        except Exception as exc:
            logging.exception("Failed to load actual-autoseg case")
            slicer.util.errorDisplay(str(exc))

    def updateVisibility(self, *_args):
        ct = self.loadedNodes.get("ct")
        if ct and ct.GetDisplayNode():
            ct.GetDisplayNode().SetVisibility(bool(self.showCT.checked))
        thickness = max(1, int(round(float(self.thickness.value))))
        fill = float(self.opacity.value)
        for node_key, ids, checks, diag in (
            ("seg", self.primaryIds, self.primaryChecks, False),
            ("diag", self.diagIds, self.diagChecks, True),
        ):
            node = self.loadedNodes.get(node_key)
            if not node or not node.GetDisplayNode():
                continue
            display = node.GetDisplayNode()
            display.SetVisibility(True)
            display.SetVisibility2D(True)
            display.SetVisibility3D(bool(self.show3D.checked))
            try:
                display.SetSliceIntersectionThickness(thickness)
            except Exception:
                pass
            for key, segId in ids.items():
                display.SetSegmentVisibility(segId, bool(checks[key].checked))
                try:
                    display.SetSegmentOpacity2DFill(segId, 0.20 if diag else fill)
                    display.SetSegmentOpacity2DOutline(segId, 1.0)
                    display.SetSegmentOpacity3D(segId, 0.40 if diag else 0.55)
                except Exception:
                    pass

    def fitViews(self):
        try:
            slicer.util.resetSliceViews()
        except Exception:
            pass

    def clearLoadedNodes(self):
        for key in ("diag", "seg", "ct"):
            node = self.loadedNodes.get(key)
            if node:
                try:
                    slicer.mrmlScene.RemoveNode(node)
                except Exception:
                    pass
        self.loadedNodes = {"ct": None, "seg": None, "diag": None}
        self.primaryIds = {}
        self.diagIds = {}


class ActualAutosegNSRQAViewerLogic(ScriptedLoadableModuleLogic):
    @staticmethod
    def patientSortKey(pid):
        try:
            return (0, int(pid))
        except Exception:
            return (1, str(pid).lower())

    def scanRoot(self, root: Path):
        result = {}
        if not root.is_dir():
            return result
        for p in root.glob("*/*/*/patient_*"):
            if not p.is_dir() or not (p / "autoseg_input.nii.gz").is_file():
                continue
            try:
                mode, roi, split, patient_dir = p.relative_to(root).parts
            except ValueError:
                continue
            pid = patient_dir.replace("patient_", "", 1)
            result.setdefault(mode, {}).setdefault(roi, {}).setdefault(split, {})[pid] = p
        return result

    def countCases(self, index):
        return sum(
            len(patients)
            for rois in index.values()
            for splits in rois.values()
            for patients in splits.values()
        )

    def _loadLabel(self, path: Path, node, name, color, reference):
        if not path.is_file():
            return None
        label = slicer.util.loadLabelVolume(str(path))
        if not label:
            raise RuntimeError(f"Could not load labelmap: {path}")
        try:
            seg = node.GetSegmentation()
            before = {seg.GetNthSegmentID(i) for i in range(seg.GetNumberOfSegments())}
            node.SetReferenceImageGeometryParameterFromVolumeNode(reference)
            slicer.modules.segmentations.logic().ImportLabelmapToSegmentationNode(label, node)
            after = [seg.GetNthSegmentID(i) for i in range(seg.GetNumberOfSegments())]
            newIds = [sid for sid in after if sid not in before]
            if not newIds:
                return None
            sid = newIds[-1]
            segment = seg.GetSegment(sid)
            segment.SetName(name)
            segment.SetColor(*[float(c) for c in color])
            return sid
        finally:
            slicer.mrmlScene.RemoveNode(label)

    def _newSegmentation(self, name, ct):
        node = slicer.mrmlScene.AddNewNodeByClass("vtkMRMLSegmentationNode")
        node.SetName(name)
        node.CreateDefaultDisplayNodes()
        node.SetReferenceImageGeometryParameterFromVolumeNode(ct)
        return node

    def loadCase(self, caseDir: Path, roi: str, pid: str):
        ctPath = caseDir / "ct.nii.gz"
        if not ctPath.is_file():
            raise FileNotFoundError(ctPath)
        ct = slicer.util.loadVolume(str(ctPath))
        if not ct:
            raise RuntimeError(f"Could not load CT: {ctPath}")
        ct.SetName(f"CT-{roi}-patient_{pid}")

        seg = self._newSegmentation(f"AutosegNSRQA-{roi}-patient_{pid}", ct)
        diag = self._newSegmentation(f"AutosegDiagnostics-{roi}-patient_{pid}", ct)
        primaryIds, diagIds, missing = {}, {}, []
        for key, name, filename, color in PRIMARY_SPECS:
            path = caseDir / filename
            sid = self._loadLabel(path, seg, name, color, ct)
            if sid:
                primaryIds[key] = sid
            else:
                missing.append(filename)
        for key, name, filename, color in DIAGNOSTIC_SPECS:
            path = caseDir / filename
            sid = self._loadLabel(path, diag, name, color, ct)
            if sid:
                diagIds[key] = sid
            else:
                missing.append(filename)
        try:
            seg.CreateClosedSurfaceRepresentation()
            diag.CreateClosedSurfaceRepresentation()
        except Exception:
            pass
        return ct, seg, primaryIds, diag, diagIds, missing

    def formatMetrics(self, caseDir: Path):
        path = caseDir / "metrics.json"
        if not path.is_file():
            return "metrics.json has not been generated for this case."
        data = json.loads(path.read_text(encoding="utf-8"))
        def fmt(key, digits=4):
            value = data.get(key)
            return "NA" if value is None else f"{float(value):.{digits}f}"
        return (
            f"True autoseg error (autoseg vs approved)\n"
            f"  1-Dice: {fmt('true_1_minus_dice')}\n"
            f"  HD95:   {fmt('true_hd95_mm', 3)} mm\n"
            f"  ASSD:   {fmt('true_assd_mm', 3)} mm\n"
            f"  RelVol: {fmt('true_relative_volume_difference')}\n\n"
            f"NSR-QA disagreement (autoseg vs reconstruction)\n"
            f"  1-Dice: {fmt('qa_1_minus_dice')}\n"
            f"  HD95:   {fmt('qa_hd95_mm', 3)} mm\n"
            f"  ASSD:   {fmt('qa_assd_mm', 3)} mm\n"
            f"  RelVol: {fmt('qa_relative_volume_difference')}"
        )


