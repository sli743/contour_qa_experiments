#!/usr/bin/env python3
"""Prepare a controlled Lung_L NSR-QA corruption-vs-identity training ablation.

The corruption arm uses the severity-calibrated *original final NSR-QA* family
set.  The baseline uses the exact same trainer/model/loss/data split, but every
training/validation input is left clean (clean_probability=1.0).

No cut/truncation or other new corruption family is introduced here.  This is
intended to test whether the benchmark-independent NSR-QA corruption principle
transfers to real autosegmentations before adding anatomy-specific failures.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
from typing import Dict, Iterable, List

import yaml


EXPECTED_BRANCHES = {
    "smooth_warp": 0.10,
    "distance_noise": 0.20,
    "combined": 0.15,
    "stochastic_region_dropout": 0.20,
    "global_boundary_offset": 0.15,
}
EXPECTED_CLEAN = 0.20
DEFAULT_SEEDS = [91, 92, 93]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--calibrated-config",
        default=(
            "/scratch/shaohan/contour_QA/lung_l_nsrqa_severity_calibration_v1/"
            "recommended_training_config.yaml"
        ),
        help="Severity-calibrated Lung_L NSR-QA config generated by calibrate_lung_l_nsrqa_severity.py",
    )
    p.add_argument(
        "--study-root",
        default="/scratch/shaohan/contour_QA/lung_l_nsrqa_corruption_ablation_v1",
    )
    p.add_argument("--seeds", nargs="+", type=int, default=DEFAULT_SEEDS)
    return p.parse_args()


def close(a: float, b: float, tol: float = 1e-8) -> bool:
    return abs(float(a) - float(b)) <= tol


def validate_original_family_set(cfg: Dict) -> None:
    if "stochastic_region_dropout" not in cfg:
        raise KeyError("Calibrated config has no stochastic_region_dropout section")
    spec = cfg["stochastic_region_dropout"]
    clean = float(spec.get("clean_probability", -1.0))
    if not close(clean, EXPECTED_CLEAN):
        raise ValueError(
            f"Expected original NSR-QA clean_probability={EXPECTED_CLEAN}, got {clean}. "
            "This experiment intentionally freezes the original family mixture."
        )
    got = spec.get("branch_probabilities", {})
    missing = [k for k in EXPECTED_BRANCHES if k not in got]
    if missing:
        raise KeyError(f"Missing original NSR-QA branch probabilities: {missing}")
    mismatched = {
        k: {"expected": v, "got": float(got[k])}
        for k, v in EXPECTED_BRANCHES.items()
        if not close(float(got[k]), v)
    }
    extra = sorted(set(got) - set(EXPECTED_BRANCHES))
    if mismatched or extra:
        raise ValueError(
            "Calibrated config no longer matches the frozen original NSR-QA family set. "
            f"mismatched={mismatched}, extra={extra}"
        )

    required = ["smooth_warp", "distance_noise", "dropout", "global_boundary_offset"]
    absent = [k for k in required if k not in spec]
    if absent:
        raise KeyError(f"Calibrated config missing corruption parameter blocks: {absent}")


def arm_config(base: Dict, study_root: Path, arm: str, seed: int) -> Dict:
    cfg = copy.deepcopy(base)
    cfg["seed"] = int(seed)
    cfg["corruption_backend"] = "legacy_stochastic_region_dropout"
    cfg["output_root"] = str(study_root / "models" / arm)
    cfg["experiment_name"] = f"lung_l_{arm}_seed{seed}"

    spec = cfg["stochastic_region_dropout"]
    if arm == "nsrqa_corruption":
        # Preserve calibrated severity and the original final NSR-QA mixture exactly.
        spec["clean_probability"] = EXPECTED_CLEAN
        spec["branch_probabilities"] = copy.deepcopy(EXPECTED_BRANCHES)
        intervention = (
            "Original final NSR-QA corruption families/probabilities with Lung_L "
            "severity calibrated from current training1 real-error geometry."
        )
    elif arm == "no_corruption":
        # random.Random.random() is in [0,1), therefore this always selects clean.
        # Keep all latent branch parameters in the config so every other setting
        # stays byte-for-byte comparable where possible.
        spec["clean_probability"] = 1.0
        spec["branch_probabilities"] = copy.deepcopy(EXPECTED_BRANCHES)
        intervention = (
            "Identity-input baseline: no synthetic corruption is inserted into training "
            "or validation; same trainer, model, loss weights, data splits and optimizer."
        )
    else:
        raise ValueError(arm)

    meta = cfg.setdefault("study_metadata", {})
    meta.update({
        "experiment": "Lung_L real-autoseg NSR-QA corruption ablation",
        "arm": arm,
        "seed": int(seed),
        "intervention": intervention,
        "new_corruption_families_added": False,
        "explicit_cut_training": False,
        "primary_real_world_question": (
            "Does benchmark-independent NSR-QA corruption training improve ranking signals "
            "on real Lung_L autosegmentations relative to identity-only training?"
        ),
        "baseline_note": (
            "In the no-corruption arm changed==0. The unchanged changed-region BCE reduces "
            "to ordinary BCE; this deliberately preserves the same training code path."
        ),
    })
    return cfg


def write_manifest(rows: List[Dict], path: Path) -> None:
    import csv
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    args = parse_args()
    calibrated = Path(args.calibrated_config).expanduser().resolve()
    if not calibrated.is_file():
        raise FileNotFoundError(
            f"Calibrated training config not found: {calibrated}\n"
            "Run the Lung_L NSR-QA severity calibration first."
        )
    base = yaml.safe_load(calibrated.read_text(encoding="utf-8"))
    validate_original_family_set(base)

    study_root = Path(args.study_root).expanduser().resolve()
    config_dir = study_root / "configs"
    config_dir.mkdir(parents=True, exist_ok=True)
    (study_root / "models").mkdir(parents=True, exist_ok=True)
    (study_root / "evaluations").mkdir(parents=True, exist_ok=True)

    seeds = [int(s) for s in args.seeds]
    if len(set(seeds)) != len(seeds):
        raise ValueError(f"Seeds must be unique: {seeds}")

    rows: List[Dict] = []
    for arm in ("nsrqa_corruption", "no_corruption"):
        for seed in seeds:
            cfg = arm_config(base, study_root, arm, seed)
            out = config_dir / f"{arm}_seed{seed}.yaml"
            out.write_text(yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            rows.append({
                "task_index": len(rows),
                "arm": arm,
                "seed": seed,
                "config": str(out),
                "experiment_name": cfg["experiment_name"],
                "model_dir": str(Path(cfg["output_root"]) / cfg["experiment_name"]),
                "checkpoint": str(Path(cfg["output_root"]) / cfg["experiment_name"] / "checkpoints" / "best_decoder.pth"),
            })

    manifest = study_root / "experiment_manifest.csv"
    write_manifest(rows, manifest)
    metadata = {
        "source_calibrated_config": str(calibrated),
        "study_root": str(study_root),
        "seeds": seeds,
        "arms": ["nsrqa_corruption", "no_corruption"],
        "frozen_original_nsrqa_clean_probability": EXPECTED_CLEAN,
        "frozen_original_nsrqa_branch_probabilities": EXPECTED_BRANCHES,
        "primary_qa_signal": "autoseg vs reconstruction 1-Dice",
        "secondary_qa_signals": ["HD95", "ASSD", "relative volume difference"],
        "evaluation_note": (
            "Manual contour-behavior domains/review priority are intentionally not used here; "
            "scores are frozen first, then cases can be visually adjudicated."
        ),
    }
    (study_root / "experiment_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print(f"Prepared {len(rows)} runs under {study_root}")
    print(f"Manifest: {manifest}")
    for row in rows:
        print(f"  [{row['task_index']}] {row['arm']} seed={row['seed']} -> {row['config']}")


if __name__ == "__main__":
    main()
