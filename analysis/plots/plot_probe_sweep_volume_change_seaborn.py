#!/usr/bin/env python3
"""
Plot probe severity sweep metrics against amount of volume change.

Input
-----
One or more probe_eval_sweep_detailed.csv files generated by
eval_post_dae_probe_sitk_morph_sweep_v2.py.

The script computes:
  signed_volume_change_frac = (input_voxels - target_voxels) / target_voxels
  abs_volume_change_frac    = abs(input_voxels - target_voxels) / target_voxels
  signed_volume_change_pct  = 100 * signed_volume_change_frac
  abs_volume_change_pct     = 100 * abs_volume_change_frac

Then it generates seaborn line plots with error bands:
  x-axis: volume change
  y-axis: requested metrics
  one plot per probe_type and metric.

Examples
--------
python plot_probe_sweep_volume_change_seaborn.py \
  --csvs /scratch/.../probe_eval_sweep/probe_eval_sweep_detailed.csv \
  --out_dir /scratch/.../probe_eval_sweep/volume_change_plots

Combined bronchus FOVs:
python plot_probe_sweep_volume_change_seaborn.py \
  --csvs /scratch/.../label_ae_bronchus*/probe_eval_sweep/probe_eval_sweep_detailed.csv \
  --out_dir ../radformation-data/fov_sensitivity_airway_roiwise/aggregate/volume_change_plots \
  --hue fov
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import List, Optional

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns


DEFAULT_METRICS = [
    "dice_input_vs_target",
    "dice_input_vs_recon",
    "dice_recon_vs_target",
    "hd95_input_vs_target",
    "hd95_input_vs_recon",
    "hd95_recon_vs_target",
]

PREFERRED_PROBE_ORDER = [
    "clean",
    "shifted",
    "eroded",
    "dilated",
    "cut_lower",
    "cut_upper",
    "cut_posterior",
    "cut_lower_half",
    "cut_upper_half",
    "cut_posterior_half",
    "big_bite",
    "big_blob",
]


def sanitize(s: str) -> str:
    s = str(s)
    s = re.sub(r"[^A-Za-z0-9_.+-]+", "_", s)
    return s.strip("_") or "value"


def infer_run_name(csv_path: Path) -> str:
    # Expected: .../<experiment>/probe_eval_sweep/probe_eval_sweep_detailed.csv
    try:
        return csv_path.parent.parent.name
    except Exception:
        return csv_path.stem


def infer_roi_from_exp(exp_name: str) -> str:
    known = [
        "Bronchus", "Lung_L", "Lung_R", "Heart", "Esophagus", "SpinalCord",
        "Liver", "Stomach", "A_Aorta", "A_Pulmonary", "Trachea", "Carina",
        "BrachPlx_L", "BrachPlx_R", "Ribs", "V_VenaCava_S", "NS_Chestwall",
    ]
    low = exp_name.lower()
    for roi in known:
        if roi.lower() in low:
            return roi
    return "unknown_roi"


def load_all(csvs: List[str]) -> pd.DataFrame:
    frames = []
    for raw in csvs:
        p = Path(raw)
        if not p.exists():
            print(f"WARNING: missing CSV, skipping: {p}")
            continue
        df = pd.read_csv(p)
        if df.empty:
            print(f"WARNING: empty CSV, skipping: {p}")
            continue

        if "source_csv" not in df.columns:
            df["source_csv"] = str(p)
        if "run_name" not in df.columns:
            df["run_name"] = infer_run_name(p)

        # Prefer existing exp_name/fov if present, but fill missing.
        if "exp_name" not in df.columns:
            df["exp_name"] = df["run_name"]
        df["exp_name"] = df["exp_name"].fillna(df["run_name"])

        if "roi" not in df.columns:
            df["roi"] = df["exp_name"].astype(str).map(infer_roi_from_exp)

        if "fov" not in df.columns:
            df["fov"] = df["run_name"]

        frames.append(df)

    if not frames:
        raise FileNotFoundError("No valid CSV files were loaded.")
    return pd.concat(frames, ignore_index=True)


def add_volume_change_columns(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    for c in ["input_voxels", "target_voxels", "recon_voxels"]:
        if c not in out.columns:
            raise ValueError(f"Required column missing: {c}")
        out[c] = pd.to_numeric(out[c], errors="coerce")

    denom = out["target_voxels"].replace(0, np.nan)
    out["signed_volume_change_frac"] = (out["input_voxels"] - out["target_voxels"]) / denom
    out["abs_volume_change_frac"] = out["signed_volume_change_frac"].abs()
    out["signed_volume_change_pct"] = 100.0 * out["signed_volume_change_frac"]
    out["abs_volume_change_pct"] = 100.0 * out["abs_volume_change_frac"]

    out["recon_signed_volume_change_frac"] = (out["recon_voxels"] - out["target_voxels"]) / denom
    out["recon_abs_volume_change_frac"] = out["recon_signed_volume_change_frac"].abs()
    out["recon_signed_volume_change_pct"] = 100.0 * out["recon_signed_volume_change_frac"]
    out["recon_abs_volume_change_pct"] = 100.0 * out["recon_abs_volume_change_frac"]

    return out


def maybe_filter_inf(df: pd.DataFrame, metric: str, drop_inf: bool) -> pd.DataFrame:
    out = df.copy()
    out[metric] = pd.to_numeric(out[metric], errors="coerce")
    if drop_inf:
        out = out[np.isfinite(out[metric])].copy()
    return out


def ordered_probe_types(values) -> List[str]:
    vals = [str(v) for v in pd.unique(pd.Series(values).dropna())]
    ordered = [p for p in PREFERRED_PROBE_ORDER if p in vals]
    ordered.extend([p for p in vals if p not in ordered])
    return ordered


def lineplot_with_errorband(
    data: pd.DataFrame,
    x: str,
    y: str,
    hue: Optional[str],
    error: str,
    marker: str,
):
    # Seaborn >=0.12 uses errorbar; older versions use ci.
    kwargs = dict(data=data, x=x, y=y, marker=marker)
    if hue and hue in data.columns and data[hue].nunique(dropna=True) > 1:
        kwargs["hue"] = hue

    try:
        if error == "sd":
            sns.lineplot(**kwargs, errorbar="sd")
        elif error == "se":
            sns.lineplot(**kwargs, errorbar="se")
        elif error == "ci95":
            sns.lineplot(**kwargs, errorbar=("ci", 95))
        else:
            sns.lineplot(**kwargs, errorbar=None)
    except Exception:
        # Older seaborn fallback.
        if error == "sd":
            sns.lineplot(**kwargs, ci="sd")
        elif error == "ci95":
            sns.lineplot(**kwargs, ci=95)
        else:
            sns.lineplot(**kwargs, ci=None)


def make_plots(
    df: pd.DataFrame,
    out_dir: Path,
    metrics: List[str],
    x_col: str,
    hue: Optional[str],
    error: str,
    drop_inf: bool,
    min_n: int,
    dpi: int,
):
    out_dir.mkdir(parents=True, exist_ok=True)

    available_metrics = [m for m in metrics if m in df.columns]
    missing = [m for m in metrics if m not in df.columns]
    if missing:
        print(f"WARNING: missing metrics skipped: {missing}")

    all_plot_rows = []

    for probe in ordered_probe_types(df["probe_type"]):
        sub_probe = df[df["probe_type"].astype(str) == probe].copy()
        if len(sub_probe) < min_n:
            print(f"Skipping {probe}: only {len(sub_probe)} rows")
            continue

        for metric in available_metrics:
            sub = maybe_filter_inf(sub_probe, metric, drop_inf=drop_inf)
            sub = sub[np.isfinite(pd.to_numeric(sub[x_col], errors="coerce"))].copy()
            sub[metric] = pd.to_numeric(sub[metric], errors="coerce")
            sub[x_col] = pd.to_numeric(sub[x_col], errors="coerce")
            sub = sub.dropna(subset=[x_col, metric])

            if len(sub) < min_n:
                print(f"Skipping {probe}/{metric}: only {len(sub)} finite rows")
                continue

            # Save summarized values used by seaborn for traceability.
            group_cols = ["probe_type", x_col]
            if hue and hue in sub.columns:
                group_cols.append(hue)
            summary = (
                sub.groupby(group_cols, dropna=False)[metric]
                .agg(["mean", "std", "count", "median", "min", "max"])
                .reset_index()
            )
            summary["metric"] = metric
            all_plot_rows.append(summary)

            plt.figure(figsize=(9.5, 6.0))
            lineplot_with_errorband(
                data=sub,
                x=x_col,
                y=metric,
                hue=hue,
                error=error,
                marker="o",
            )

            xlabel = {
                "abs_volume_change_pct": "Absolute input volume change (%)",
                "signed_volume_change_pct": "Signed input volume change (%)",
                "recon_abs_volume_change_pct": "Absolute recon volume change (%)",
                "recon_signed_volume_change_pct": "Signed recon volume change (%)",
            }.get(x_col, x_col)

            ylabel = metric.replace("_", " ")
            plt.xlabel(xlabel, fontsize=12)
            plt.ylabel(ylabel, fontsize=12)
            plt.title(f"{ylabel} vs volume change | {probe}", fontsize=14)
            plt.grid(alpha=0.3)
            if hue and hue in sub.columns and sub[hue].nunique(dropna=True) > 1:
                plt.legend(loc="center left", bbox_to_anchor=(1.02, 0.5), fontsize=9)
            plt.tight_layout()

            out_path = out_dir / f"{sanitize(probe)}__{sanitize(metric)}__vs_{sanitize(x_col)}.png"
            plt.savefig(out_path, dpi=dpi)
            plt.close()

    if all_plot_rows:
        plot_table = pd.concat(all_plot_rows, ignore_index=True)
        plot_table.to_csv(out_dir / f"volume_change_plot_summary_by_{sanitize(x_col)}.csv", index=False)


def make_facet_metric_grid(
    df: pd.DataFrame,
    out_dir: Path,
    metric: str,
    x_col: str,
    hue: Optional[str],
    error: str,
    drop_inf: bool,
    dpi: int,
):
    """Optional overview: one FacetGrid per metric with columns=probe_type."""
    if metric not in df.columns:
        return
    sub = maybe_filter_inf(df, metric, drop_inf=drop_inf)
    sub = sub[np.isfinite(pd.to_numeric(sub[x_col], errors="coerce"))].copy()
    sub[metric] = pd.to_numeric(sub[metric], errors="coerce")
    sub[x_col] = pd.to_numeric(sub[x_col], errors="coerce")
    sub = sub.dropna(subset=[x_col, metric])
    if sub.empty:
        return

    probes = ordered_probe_types(sub["probe_type"])
    sub["probe_type"] = pd.Categorical(sub["probe_type"].astype(str), categories=probes, ordered=True)

    # Use relplot because it supports errorbar/ci.
    try:
        g = sns.relplot(
            data=sub,
            x=x_col,
            y=metric,
            hue=hue if hue in sub.columns else None,
            col="probe_type",
            col_wrap=3,
            kind="line",
            marker="o",
            errorbar=("ci", 95) if error == "ci95" else error if error in {"sd", "se"} else None,
            facet_kws={"sharey": False, "sharex": True},
            height=3.4,
            aspect=1.25,
        )
    except Exception:
        g = sns.relplot(
            data=sub,
            x=x_col,
            y=metric,
            hue=hue if hue in sub.columns else None,
            col="probe_type",
            col_wrap=3,
            kind="line",
            marker="o",
            ci=95 if error == "ci95" else "sd" if error == "sd" else None,
            facet_kws={"sharey": False, "sharex": True},
            height=3.4,
            aspect=1.25,
        )

    g.set_axis_labels(x_col.replace("_", " "), metric.replace("_", " "))
    g.fig.suptitle(f"{metric.replace('_', ' ')} vs volume change", y=1.02)
    out_path = out_dir / f"facet__{sanitize(metric)}__vs_{sanitize(x_col)}.png"
    g.savefig(out_path, dpi=dpi, bbox_inches="tight")
    plt.close(g.fig)


def main() -> None:
    p = argparse.ArgumentParser(description="Seaborn line plots of probe metrics versus volume change.")
    p.add_argument("--csvs", nargs="+", required=True, help="One or more probe_eval_sweep_detailed.csv files.")
    p.add_argument("--out_dir", required=True)
    p.add_argument("--metrics", nargs="+", default=DEFAULT_METRICS)
    p.add_argument(
        "--x_col",
        default="abs_volume_change_pct",
        choices=[
            "abs_volume_change_pct",
            "signed_volume_change_pct",
            "recon_abs_volume_change_pct",
            "recon_signed_volume_change_pct",
        ],
    )
    p.add_argument("--hue", default="fov", help="Column used for separate lines. Use 'none' to disable.")
    p.add_argument("--error", choices=["ci95", "sd", "se", "none"], default="ci95")
    p.add_argument("--drop_inf", action="store_true", help="Drop inf metric values before plotting.")
    p.add_argument("--min_n", type=int, default=3)
    p.add_argument("--dpi", type=int, default=300)
    p.add_argument("--facet_overview", action="store_true", help="Also write one facet overview per metric.")
    args = p.parse_args()

    out_dir = Path(args.out_dir)
    sns.set_theme(style="whitegrid", context="talk")

    df = load_all(args.csvs)
    df = add_volume_change_columns(df)

    # Normalize hue option.
    hue = None if str(args.hue).lower() in {"none", "", "false", "0"} else args.hue
    if hue and hue not in df.columns:
        print(f"WARNING: hue column '{hue}' not found; disabling hue.")
        hue = None

    out_dir.mkdir(parents=True, exist_ok=True)
    combined_csv = out_dir / "combined_probe_sweep_with_volume_change.csv"
    df.to_csv(combined_csv, index=False)

    make_plots(
        df=df,
        out_dir=out_dir,
        metrics=args.metrics,
        x_col=args.x_col,
        hue=hue,
        error=args.error,
        drop_inf=args.drop_inf,
        min_n=args.min_n,
        dpi=args.dpi,
    )

    if args.facet_overview:
        for metric in args.metrics:
            make_facet_metric_grid(
                df=df,
                out_dir=out_dir,
                metric=metric,
                x_col=args.x_col,
                hue=hue,
                error=args.error,
                drop_inf=args.drop_inf,
                dpi=args.dpi,
            )

    readme = out_dir / "README_volume_change_plots.md"
    readme.write_text(
        "# Probe sweep volume-change plots\\n\\n"
        f"- Input CSV count: {len(args.csvs)}\\n"
        f"- X-axis: `{args.x_col}`\\n"
        f"- Hue: `{hue}`\\n"
        f"- Error band: `{args.error}`\\n"
        f"- Combined table: `{combined_csv.name}`\\n\\n"
        "Each PNG is named as:\\n"
        "`<probe_type>__<metric>__vs_<x_col>.png`\\n",
        encoding="utf-8",
    )

    print(f"Loaded rows: {len(df)}")
    print(f"Wrote combined CSV: {combined_csv}")
    print(f"Wrote plots to: {out_dir}")


if __name__ == "__main__":
    main()
